import { amocrmOAuth2RuntimeConfig } from './amocrm-oauth2.js';

/**
 * Shared by every amoCRM activity — emitted once by `compileActivities` (see
 * `IWorkflowIntegration.sharedActivityCode`) so it isn't redeclared per activity, which would
 * collide once concatenated into one activities.ts module. Every declared name is `amocrm`-prefixed
 * for the same reason (other vendors' shared code lands in the same module).
 *
 * `amocrmRequest` is the one place an amoCRM HTTP call is made, mirroring what the official PHP
 * client (`amocrm/amocrm-api-php`'s `AmoCRMApiRequest`) does:
 * - `https://<account domain>/api/v4/...` with `Authorization: Bearer <access token>`; the token comes
 *   from the backend, which refreshes it with the platform OAuth2 client;
 * - the query string is built PHP `http_build_query`-style (`filter[id][0]=1`, `order[created_at]=asc`,
 *   booleans as `1`/`0`), which is what amoCRM's `filter`/`order` parameters expect;
 * - HTTP 204 (amoCRM's answer for "nothing found", e.g. an empty list or an unknown id) resolves to
 *   `null` instead of failing on an empty body;
 * - a 4xx other than 408/429 is a non-retryable `ApplicationFailure` (Temporal would otherwise retry a
 *   validation error or a revoked token forever); 429 (amoCRM allows ~7 requests/second per account)
 *   and 5xx stay retryable.
 */
export const AMOCRM_SHARED_ACTIVITY_CODE = [
  "import { ApplicationFailure } from '@temporalio/activity';",
  "import { resolveOAuth2AccessToken } from '@falang/workflow-integrations-common';",
  '',
  // `as const` keeps `tokenRequestFormat` narrowed to `'json'` instead of widening to `string`
  // — without it, `resolveOAuth2AccessToken`'s `IOAuth2RuntimeConfig` parameter type rejects this
  // object and the project's type check fails.
  `const AMOCRM_OAUTH2_CONFIG = ${JSON.stringify(amocrmOAuth2RuntimeConfig)} as const;`,
  '',
  '// A valid access token from the backend, which refreshes it with the platform OAuth2 client',
  "// (handling amoCRM's account-domain/JSON-body/redirect-uri-on-refresh deviations from RFC 6749).",
  'const resolveAmoCrmAccessToken = (credentialId: string): Promise<string> =>',
  "  resolveOAuth2AccessToken('amocrm', credentialId, AMOCRM_OAUTH2_CONFIG);",
  '',
  '// Resolves a plain (non-OAuth2) credentialId+field -> real value, same mechanism as',
  "// telegram.integration.ts's resolveTelegramBotToken / openai.integration.ts's resolveOpenAiField.",
  '// OAuth2 credential fields (the account domain included) only ever live in the dev slot.',
  'const resolveAmoCrmField = async (credentialId: string, field: string): Promise<string> => {',
  '  const backendUrl = process.env.BACKEND_INTERNAL_URL;',
  '  const internalProjectToken = process.env.INTERNAL_PROJECT_TOKEN;',
  '  const projectId = process.env.PROJECT_ID;',
  '  if (!backendUrl || !internalProjectToken || !projectId) {',
  "    throw new Error('BACKEND_INTERNAL_URL/INTERNAL_PROJECT_TOKEN/PROJECT_ID are not configured for this runner process');",
  '  }',
  '  const response = await fetch(`${backendUrl}/internal/credentials/resolve`, {',
  "    method: 'POST',",
  "    headers: { 'Content-Type': 'application/json', 'x-internal-project-token': internalProjectToken },",
  "    body: JSON.stringify({ credentialId, vendor: 'amocrm', field, projectId, env: 'dev' }),",
  '  });',
  '  if (!response.ok) {',
  '    throw new Error(`Failed to resolve amoCRM credential ${credentialId}/${field}: ${response.status} ${await response.text()}`);',
  '  }',
  '  const data = (await response.json()) as { value: string };',
  '  return data.value;',
  '};',
  '',
  '// PHP http_build_query semantics: nested objects/arrays become bracketed keys, booleans 1/0, null/undefined skipped.',
  'const amocrmAppendQuery = (params: URLSearchParams, key: string, value: unknown): void => {',
  '  if (value === undefined || value === null) return;',
  '  if (Array.isArray(value)) {',
  '    value.forEach((item, index) => amocrmAppendQuery(params, `${key}[${index}]`, item));',
  '    return;',
  '  }',
  "  if (typeof value === 'object') {",
  '    for (const [childKey, childValue] of Object.entries(value as Record<string, unknown>)) {',
  '      amocrmAppendQuery(params, `${key}[${childKey}]`, childValue);',
  '    }',
  '    return;',
  '  }',
  "  if (typeof value === 'boolean') {",
  "    params.append(key, value ? '1' : '0');",
  '    return;',
  '  }',
  '  params.append(key, String(value));',
  '};',
  '',
  'const amocrmBuildQuery = (query: Record<string, unknown> | undefined): string => {',
  '  const params = new URLSearchParams();',
  '  for (const [key, value] of Object.entries(query ?? {})) amocrmAppendQuery(params, key, value);',
  '  const text = params.toString();',
  "  return text ? `?${text}` : '';",
  '};',
  '',
  '// A positive integer id for a URL path segment — anything else is a workflow bug, not worth retrying.',
  'const amocrmId = (id: unknown): string => {',
  '  const value = Number(id);',
  '  if (!Number.isInteger(value) || value <= 0) {',
  "    throw ApplicationFailure.nonRetryable(`amoCRM: invalid id ${String(id)}`, 'AMOCRM_INVALID_ARGUMENT');",
  '  }',
  '  return String(value);',
  '};',
  '',
  '// An entity type path segment (leads, contacts, companies, customers, catalogs, …).',
  'const amocrmEntityType = (value: unknown): string => {',
  "  if (typeof value !== 'string' || !/^[a-z_]+$/.test(value)) {",
  "    throw ApplicationFailure.nonRetryable(`amoCRM: invalid entity type ${String(value)}`, 'AMOCRM_INVALID_ARGUMENT');",
  '  }',
  '  return value;',
  '};',
  '',
  'const amocrmRequest = async (',
  '  credentialId: string,',
  '  httpMethod: string,',
  '  path: string,',
  '  query?: Record<string, unknown>,',
  '  body?: unknown,',
  '): Promise<any> => {',
  '  const [accessToken, accountDomain] = await Promise.all([',
  '    resolveAmoCrmAccessToken(credentialId),',
  "    resolveAmoCrmField(credentialId, 'account_domain'),",
  '  ]);',
  '  const headers: Record<string, string> = { Authorization: `Bearer ${accessToken}` };',
  "  if (body !== undefined) headers['Content-Type'] = 'application/json';",
  '  const response = await fetch(`https://${accountDomain}${path}${amocrmBuildQuery(query)}`, {',
  '    method: httpMethod,',
  '    headers,',
  '    body: body === undefined ? undefined : JSON.stringify(body),',
  '  });',
  '  if (response.status === 204) return null;',
  '  const text = await response.text();',
  '  if (!response.ok) {',
  '    const message = `amoCRM ${httpMethod} ${path} failed: ${response.status} ${text.slice(0, 2000)}`;',
  '    if (response.status >= 400 && response.status < 500 && response.status !== 408 && response.status !== 429) {',
  '      throw ApplicationFailure.nonRetryable(message, `AMOCRM_HTTP_${response.status}`);',
  '    }',
  '    throw new Error(message);',
  '  }',
  '  if (!text) return null;',
  '  try {',
  '    return JSON.parse(text);',
  '  } catch {',
  '    return text;',
  '  }',
  '};',
  '',
  '// `_embedded.<key>` of a HAL response as an array — `[]` for a 204 (amoCRM: nothing found).',
  'const amocrmEmbedded = (response: any, key: string): any[] => {',
  '  const items = response?._embedded?.[key];',
  '  return Array.isArray(items) ? items : [];',
  '};',
  '',
  '// The id of the first entity a POST created (`_embedded.<key>[0].id`).',
  'const amocrmCreatedId = (response: any, key: string): { id: number } => {',
  '  const created = amocrmEmbedded(response, key)[0];',
  "  if (!created || typeof created.id !== 'number') {",
  '    throw new Error(`amoCRM: no ${key} returned`);',
  '  }',
  '  return { id: created.id };',
  '};',
  '',
  '// PHONE/EMAIL multi-fields of a contact or company (amoCRM field codes), skipped when blank.',
  'const amocrmContactFields = (phone: string | undefined, email: string | undefined): any[] => {',
  '  const fields: any[] = [];',
  "  if (phone && phone.trim()) fields.push({ field_code: 'PHONE', values: [{ value: phone.trim(), enum_code: 'WORK' }] });",
  "  if (email && email.trim()) fields.push({ field_code: 'EMAIL', values: [{ value: email.trim(), enum_code: 'WORK' }] });",
  '  return fields;',
  '};',
  '',
  '// Merges explicit top-level values and extra custom fields into an entity payload; undefined/blank values are dropped.',
  'const amocrmEntity = (',
  '  extra: Record<string, unknown> | undefined,',
  '  values: Record<string, unknown>,',
  '  customFields: any[] = [],',
  '): Record<string, unknown> => {',
  '  const entity: Record<string, unknown> = { ...(extra ?? {}) };',
  '  for (const [key, value] of Object.entries(values)) {',
  "    if (value === undefined || value === null || value === '') continue;",
  '    entity[key] = value;',
  '  }',
  '  const extraCustomFields = Array.isArray(entity.custom_fields_values) ? (entity.custom_fields_values as any[]) : [];',
  '  const allCustomFields = [...customFields, ...extraCustomFields];',
  '  if (allCustomFields.length > 0) entity.custom_fields_values = allCustomFields;',
  '  return entity;',
  '};',
].join('\n');
