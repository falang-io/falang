import type { TVariableInfo } from '@falang/typescript-dto';
import type { IIntegrationStructType } from '@falang/workflow-integrations-common';

/**
 * Hand-written struct types of the amoCRM REST API v4 (JSON keys exactly as the API sends/receives them),
 * derived from the official PHP library's models (`fromArray()` for what the API returns, `toApi()` for what
 * a write sends). Output structs (`amocrm/Lead`, …) have a required id and everything else optional; input
 * structs (`amocrm/LeadInput`, …) are all-optional and list only writable fields.
 */

const str: TVariableInfo = { type: 'string' };
const bool: TVariableInfo = { type: 'boolean' };
const int: TVariableInfo = { type: 'number', numberType: { type: 'integer', integerType: 'int64' } };
const num: TVariableInfo = { type: 'number', numberType: { type: 'any' } };
const any: TVariableInfo = { type: 'any' };
const opt = (t: TVariableInfo): TVariableInfo => ({ ...t, optional: true });
const struct = (name: string): TVariableInfo => ({ type: 'struct', id: `amocrm/${name}` });
const arrayOf = (t: TVariableInfo): TVariableInfo => ({ type: 'array', elementType: t, dimensions: 1 });
const union = (...unionTypes: TVariableInfo[]): TVariableInfo => ({ type: 'union', unionTypes });

type TProps = Record<string, TVariableInfo>;

const allOptional = (props: TProps): TProps =>
  Object.fromEntries(Object.entries(props).map(([key, value]) => [key, opt(value)]));

/** A struct whose properties are taken as written. */
const def = (name: string, properties: TProps): IIntegrationStructType => ({
  id: `amocrm/${name}`,
  name: `AmoCrm${name}`,
  properties,
});

/** An output entity: the listed key fields are required, everything else optional. */
const output = (name: string, required: TProps, rest: TProps): IIntegrationStructType =>
  def(name, { ...required, ...allOptional(rest) });

/** An input (write) struct: every property optional. */
const input = (name: string, props: TProps): IIntegrationStructType => def(name, allOptional(props));

