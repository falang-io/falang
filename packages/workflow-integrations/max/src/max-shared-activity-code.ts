  "  const current = await maxApiRequest(bot, 'GET', `messages/${encodeURIComponent(messageId)}`, {});",
  "  await maxApiRequest(bot, 'PUT', 'messages', { message_id: messageId }, { text: current?.body?.text ?? undefined, attachments: [] });",
  '};',
  '',
  'const maxSendText = async (bot: { token: string; apiBaseUrl: string }, chatId: number, text: string): Promise<any> =>',
